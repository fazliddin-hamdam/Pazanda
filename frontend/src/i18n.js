export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.uz
  return (key, vars = {}) =>
    (table[key] ?? STRINGS.uz[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`))
}

/** Telegram language_code -> ilova tili (backenddagi lang_from_code bilan bir xil). */
export function guessLang(code) {
  code = (code || '').toLowerCase()
  if (code.startsWith('tr')) return 'tr'
  if (code.startsWith('en')) return 'en'
  return 'uz'
}
